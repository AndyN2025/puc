function attachPaSlugs(blocks: ProgramBlock[]): ProgramBlock[] {
  let n = 0
  return blocks.map((block) =>
    block.map((row) => {
      n++
      const tc = row.code === '-' ? '—' : row.code
      return {
        code: `in_pa_${String(n).padStart(3, '0')}`,
        textCode: tc,
        title: row.title,
        hours: row.hours
      }
    })
  )
}

function attachPkSlugs(blocks: ProgramBlock[], startAfter: number): ProgramBlock[] {
  let n = startAfter
  return blocks.map((block) =>
    block.map((row) => {
      n++
      const tc = row.code === '-' ? '—' : row.code
      return {
        code: `in_pk_${String(n).padStart(3, '0')}`,
        textCode: tc,
        title: row.title,
        hours: row.hours
      }
    })
  )
}

